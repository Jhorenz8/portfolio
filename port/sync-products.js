// Regenerate products-data.js from live Supabase data.
// Usage: node sync-products.js
// Reads keys from config.js, fetches products via PostgREST, writes static file.
const fs = require('fs');

// Load browser-style config.js into plain object
const cfg = {};
new Function('window', fs.readFileSync(__dirname + '/config.js', 'utf8'))(cfg);

const url = cfg.SUPABASE_URL;
const key = cfg.SUPABASE_ANON_KEY;

if (!url || !key) {
    console.error('Missing SUPABASE_URL / SUPABASE_ANON_KEY in config.js');
    process.exit(1);
}

async function main() {
    const res = await fetch(`${url}/rest/v1/products?select=*&order=price.asc`, {
        headers: { apikey: key, Authorization: `Bearer ${key}` }
    });
    if (!res.ok) {
        throw new Error(`Supabase ${res.status}: ${await res.text()}`);
    }
    const rows = await res.json();
    const out =
        `// Auto-generated by sync-products.js on ${new Date().toISOString()}\n` +
        `// Preloaded products — served instantly with the store page (zero load wait).\n` +
        `// Regenerate from live data:  node sync-products.js\n` +
        `window.PRELOADED_PRODUCTS = ${JSON.stringify(rows, null, 4)};\n`;
    fs.writeFileSync(__dirname + '/products-data.js', out);
    console.log(`Wrote ${rows.length} products to products-data.js`);
}

main().catch(e => { console.error(e.message); process.exit(1); });
